-- =====================================================
-- 8. VALIDACIONES DE INTEGRIDAD
-- =====================================================

-- Verificar que todos los jobs en log tienen su entrada en progress (para jobs activos)
SELECT 
  lf.JOB_ID,
  lf.ESTADO,
  lf.FECHA_INICIO,
  CASE WHEN jp.JOB_ID IS NULL THEN 'FALTA PROGRESS' ELSE 'OK' END AS ESTADO_PROGRESS
FROM SEGSOCIAL.LOG_FUSION_DATOS lf
LEFT JOIN SEGSOCIAL.JOB_PROGRESS jp ON lf.JOB_ID = jp.JOB_ID
WHERE lf.ESTADO IN ('INICIADO', 'EN_PROCESO')
  AND lf.FECHA_INICIO > SYSTIMESTAMP - INTERVAL '1' DAY;

-- Verificar consistencia entre registros procesados y datos fusionados
SELECT 
  lf.JOB_ID,
  lf.ID_ARCHIVO,
  lf.REGISTROS_PROCESADOS AS PROCESADOS_LOG,
  lf.REGISTROS_FUSIONADOS AS FUSIONADOS_LOG,
  COUNT(df.ID) AS REGISTROS_EN_TABLA,
  CASE 
    WHEN COUNT(df.ID) = lf.REGISTROS_FUSIONADOS THEN 'OK'
    ELSE 'INCONSISTENCIA'
  END AS ESTADO_CONSISTENCIA
FROM SEGSOCIAL.LOG_FUSION_DATOS lf
LEFT JOIN SEGSOCIAL.DATOS_FUSIONADOS df ON lf.ID_ARCHIVO = df.ID_ARCHIVO AND lf.JOB_ID = df.JOB_ID
WHERE lf.ESTADO = 'COMPLETADO'
  AND lf.FECHA_INICIO > SYSTIMESTAMP - INTERVAL '7' DAY
GROUP BY lf.JOB_ID, lf.ID_ARCHIVO, lf.REGISTROS_PROCESADOS, lf.REGISTROS_FUSIONADOS
HAVING COUNT(df.ID) != lf.REGISTROS_FUSIONADOS
ORDER BY lf.FECHA_INICIO DESC;
